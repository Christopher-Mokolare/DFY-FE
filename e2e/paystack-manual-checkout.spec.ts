import { test, expect, type APIRequestContext } from '@playwright/test'

const API_BASE_URL = (process.env.DFY_API_URL || 'https://dfy-be-staging.onrender.com/api/v1').replace(/\/$/, '')
const BASE_URL = process.env.BASE_URL || 'https://dfy-fe-staging.onrender.com'
const CREATOR_EMAIL = process.env.DFY_CREATOR_EMAIL
const CREATOR_PASSWORD = process.env.DFY_CREATOR_PASSWORD
const RUNNER_EMAIL = process.env.DFY_RUNNER_EMAIL
const RUNNER_PASSWORD = process.env.DFY_RUNNER_PASSWORD

function requireManualMode() {
  test.skip(
    process.env.PAYSTACK_MANUAL_CHECKOUT !== '1',
    'Manual Paystack checkout only. Run with PAYSTACK_MANUAL_CHECKOUT=1 and --headed.'
  )
  if (process.env.PAYSTACK_MANUAL_CHECKOUT === '1') {
    requireEnv('PAYSTACK_TEST_MODE_CONFIRMED', process.env.PAYSTACK_TEST_MODE_CONFIRMED)
    expect(process.env.PAYSTACK_TEST_MODE_CONFIRMED).toBe('1')
  }
}

function requireEnv(name: string, value?: string) {
  if (!value) throw new Error(name + ' environment variable is required for the manual Paystack checkout.')
  return value
}

async function apiLogin(api: APIRequestContext, email: string, password: string) {
  const response = await api.post(`${API_BASE_URL}/auth/login`, {
    headers: { 'Content-Type': 'application/json' },
    data: { email, password },
  })
  expect(response.ok(), `Login failed: HTTP ${response.status()} body=${await response.text()}`).toBeTruthy()
  const body = await response.json()
  expect(body.success).toBeTruthy()
  const token = body.token || body.data?.token
  expect(token).toBeTruthy()
  return String(token)
}

test.setTimeout(8 * 60 * 1000)

test('manual Paystack Test Mode payment and payout reaches RunnerPaid', async ({ page, request }) => {
  requireManualMode()

  const email = requireEnv('DFY_CREATOR_EMAIL', CREATOR_EMAIL)
  const password = requireEnv('DFY_CREATOR_PASSWORD', CREATOR_PASSWORD)
  const runnerEmail = requireEnv('DFY_RUNNER_EMAIL', RUNNER_EMAIL)
  const runnerPassword = requireEnv('DFY_RUNNER_PASSWORD', RUNNER_PASSWORD)

  const apiHost = new URL(API_BASE_URL).hostname.toLowerCase()
  expect(apiHost).not.toBe('api.doforyou.co.za')
  expect(apiHost).not.toBe('doforyou.co.za')

  const creatorToken = await apiLogin(request, email, password)
  const runnerToken = await apiLogin(request, runnerEmail, runnerPassword)

  const bankResponse = await request.get(`${API_BASE_URL}/banking/accounts`, {
    headers: { Authorization: 'Bearer ' + runnerToken },
  })
  expect(bankResponse.ok(), `Runner payout settings failed: HTTP ${bankResponse.status()} body=${await bankResponse.text()}`).toBeTruthy()
  const bankBody = await bankResponse.json()
  const accounts = bankBody.data || bankBody.accounts || []
  expect(
    Array.isArray(accounts) && accounts.some((account: any) => account.isVerified === true || account.IsVerified === true),
    'The runner must have an active bank account verified with Paystack and a stored recipient reference before this test.',
  ).toBeTruthy()

  const suffix = 'MANUAL-PAYSTACK-' + Date.now()
  const create = await request.post(`${API_BASE_URL}/tasks`, {
    headers: {
      Authorization: 'Bearer ' + creatorToken,
      'Content-Type': 'application/json',
    },
    data: {
      taskName: 'DFY ' + suffix,
      taskDescription: 'Real Paystack Test Mode checkout verification ' + suffix,
      category: 'Other',
      area: 'Pretoria',
      priority: 'standard',
      dateNeeded: new Date(Date.now() + 2 * 24 * 60 * 60 * 1000).toISOString(),
      budget: 200,
      notes: 'Manual Paystack provider verification.',
      termsAccepted: true,
    },
  })

  expect(create.ok(), `Task creation failed: HTTP ${create.status()} body=${await create.text()}`).toBeTruthy()
  const body = await create.json()
  expect(body.success).toBeTruthy()

  const taskId = String(body.data?.task?.taskId || '')
  const paymentUrl = String(body.data?.paymentUrl || '')
  expect(taskId).toBeTruthy()
  expect(paymentUrl).toMatch(/^https:\/\/(checkout\.)?paystack\.com\//i)

  await page.goto(BASE_URL, { waitUntil: 'domcontentloaded', timeout: 60_000 })
  await page.evaluate((token) => localStorage.setItem('token', token), creatorToken)

  // Open the actual Paystack-hosted checkout generated by DFY.
  await page.goto(paymentUrl, { waitUntil: 'domcontentloaded', timeout: 60_000 })

  // Paystack may present a Cloudflare "Verify you are human" challenge.
  // Do not automate or bypass that security control. Complete it manually,
  // enter Paystack's documented Test Mode successful card, then resume Playwright.
  await page.pause()

  await page.waitForURL(/\/payment\/success\?taskId=/, { timeout: 120_000 })
  expect(page.url()).toContain(`/payment/success?taskId=${encodeURIComponent(taskId)}`)

  await expect.poll(async () => {
    const response = await request.get(`${API_BASE_URL}/tasks/${encodeURIComponent(taskId)}`, {
      headers: { Authorization: 'Bearer ' + creatorToken },
    })
    expect(response.ok()).toBeTruthy()
    const taskBody = await response.json()
    const task = taskBody.data
    return {
      status: String(task?.status || '').toLowerCase(),
      payment: String(task?.paymentStatus || '').toLowerCase(),
      escrow: String(task?.escrowStatus || '').toLowerCase(),
    }
  }, { timeout: 120_000, intervals: [1000, 2000, 3000, 5000] }).toMatchObject({
    status: 'posted',
    payment: 'escrowheld',
    escrow: 'held',
  })

  const claim = await request.post(`${API_BASE_URL}/tasks/${encodeURIComponent(taskId)}/claim`, {
    headers: { Authorization: 'Bearer ' + runnerToken, 'Content-Type': 'application/json' },
    data: { helperName: 'DFY E2E Runner', helperContact: '0820000000', termsAccepted: true },
  })
  expect(claim.ok(), `Runner claim failed: HTTP ${claim.status()} body=${await claim.text()}`).toBeTruthy()

  const complete = await request.post(`${API_BASE_URL}/tasks/${encodeURIComponent(taskId)}/complete`, {
    headers: { Authorization: 'Bearer ' + runnerToken, 'Content-Type': 'application/json' },
    data: {},
  })
  expect(complete.ok(), `Runner completion failed: HTTP ${complete.status()} body=${await complete.text()}`).toBeTruthy()

  const confirm = await request.post(`${API_BASE_URL}/tasks/${encodeURIComponent(taskId)}/confirm`, {
    headers: { Authorization: 'Bearer ' + creatorToken, 'Content-Type': 'application/json' },
    data: {},
  })
  expect(confirm.ok(), `Creator confirmation failed: HTTP ${confirm.status()} body=${await confirm.text()}`).toBeTruthy()

  await expect.poll(async () => {
    const response = await request.get(`${API_BASE_URL}/tasks/${encodeURIComponent(taskId)}`, {
      headers: { Authorization: 'Bearer ' + creatorToken },
    })
    expect(response.ok()).toBeTruthy()
    const task = (await response.json()).data
    return {
      status: String(task?.status || task?.taskStatus || '').toLowerCase(),
      payout: String(task?.payoutStatus || '').toLowerCase(),
    }
  }, { timeout: 4 * 60 * 1000, intervals: [2000, 5000, 10000] }).toMatchObject({
    status: 'runnerpaid',
    payout: 'completed',
  })
})
